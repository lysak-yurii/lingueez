/* The hero device stage: hover to lift, click to maximise, and the device you
   are reading this on is highlighted on arrival.

   Markup comes from _includes/hero-stage.html (generated by
   tools/site/build_hero.py). It is two parallel things:

     .dev      a <g> inside the inline SVG — what is drawn. aria-hidden.
     .dev-hit  an HTML <button> positioned over it — what is focused and
               clicked, and what carries the accessible name. An SVG
               <g tabindex="0"> is *not* focusable (Chromium leaves
               document.activeElement on <body> and Tab skips it), so the
               control has to be real HTML.

   Layout and colour live in page-home.css; this file only sets classes, one
   transform, and two custom properties.

   Depends on site.js for lzPlatform() and lzZoom(). Loaded with defer, so
   site.js has already run. */
(function(){
  var stage=document.querySelector('[data-hero-stage]');
  if(!stage) return;

  /* Devices come from the markup, not a fixed list: the home page carries all
     three, and the e-reader and Android pages carry only their own. A stage
     marked data-solo has nothing to choose between, so its device arrives
     already open with its screen switcher live. */
  var solo=stage.parentNode.getAttribute('data-solo') || null;
  var devs={}, hits={}, ORDER=[];
  Array.prototype.forEach.call(stage.querySelectorAll('.dev'), function(g){
    devs[g.getAttribute('data-dev')]=g;
  });
  Array.prototype.forEach.call(
    stage.parentNode.querySelectorAll('.dev-hit'), function(btn){
      var k=btn.getAttribute('data-hit');
      hits[k]=btn;
      if(devs[k]) ORDER.push(k);        // tab order, left to right as drawn
    });
  if(!ORDER.length) return;

  var caption=document.querySelector('[data-dev-caption]');
  var ribbon=document.querySelector('[data-ribbon]');

  /* Screens each device can show, read from the markup build_hero.py emits so
     the labels stay bilingual like every other string on the site. */
  var screens={};
  var more={};    // device key -> {href, label} for that device's own page
  var shown={};   // device key -> index of the screen currently on it
  Array.prototype.forEach.call(
    stage.parentNode.querySelectorAll('.dev-screens'), function(list){
      var key=list.getAttribute('data-screens');
      more[key]={href:list.getAttribute('data-more-href'),
                 label:(list.querySelector('.more') || {}).innerHTML || ''};
      // Which screen the markup already drew, so the caption and the dashes
      // start on the picture that is actually on the device rather than on
      // whatever happens to be first in the list.
      shown[key]=parseInt(list.getAttribute('data-start'), 10) || 0;
      screens[key]=
        Array.prototype.map.call(list.querySelectorAll('[data-screen]'), function(li){
          return {key:li.getAttribute('data-screen'),
                  light:li.getAttribute('data-light'),
                  dark:li.getAttribute('data-dark'),
                  fullLight:li.getAttribute('data-full-light'),
                  fullDark:li.getAttribute('data-full-dark'),
                  label:li.innerHTML};
        });
    });
  var reduced=window.matchMedia && window.matchMedia('(prefers-reduced-motion: reduce)').matches;
  var vb=stage.viewBox.baseVal;
  var open_=null;   // key of the maximised device, or null

  /* Caption copy. The buttons carry their own bilingual <span lang> names, so
     only this dynamic text needs a lookup here. */
  var STRINGS={
    en:{
      laptop:{name:'Desktop',   blurb:'your whole vocabulary, on your computer'},
      reader:{name:'E-reader',  blurb:'save words straight from the book you are reading'},
      phone: {name:'Phone',     blurb:'review anywhere, in your pocket'},
      hint:'Pick a device to look closer'
    },
    uk:{
      laptop:{name:'Комп’ютер', blurb:'увесь ваш словник на комп’ютері'},
      reader:{name:'Е-читач',   blurb:'зберігайте слова прямо з книжки, яку читаєте'},
      phone: {name:'Смартфон',  blurb:'повторюйте будь-де, просто в кишені'},
      hint:'Оберіть пристрій, щоб роздивитися'
    }
  };
  function strings(){
    return STRINGS[document.documentElement.getAttribute('data-lang')] || STRINGS.en;
  }

  function isDark(){
    var t=document.documentElement.getAttribute('data-theme');
    if(t) return t==='dark';
    return !!(window.matchMedia &&
              window.matchMedia('(prefers-color-scheme: dark)').matches);
  }
  /* The lightbox opens the untouched source for whichever screen is on show,
     not the hero image — that one is only as wide as the device screen. */
  function fullSrc(k){
    var scr=(screens[k] || [])[shown[k] || 0];
    if(!scr) return '';
    return isDark() ? scr.fullDark : scr.fullLight;
  }

  /* ── screens ─────────────────────────────────────────────────────────────
     Swapping a device's screen is two href writes: the SVG carries a light and
     a dark <image>, and CSS shows whichever matches the theme. Both are set so
     the picture is already right if the visitor flips the theme afterwards. */
  var swapGen=0;
  function showScreen(k, i){
    var list=screens[k];
    if(!list || !list[i]) return;
    shown[k]=i;
    var g=devs[k];
    var gen=++swapGen;

    /* Each theme has two <image> elements, front and back. The href is only
       ever written to the one that is behind: an <image> paints nothing while
       it reloads, even straight from cache, so writing to the visible element
       flashes the device empty. Preloading first is not enough — that warms the
       HTTP cache, but the element still reloads — which is why the flicker used
       to stop only after every screen had been through once. */
    function swap(theme, src, wait){
      var all=g.querySelectorAll('.screen.only-' + theme);
      if(all.length < 2){                  // older markup: nothing to swap into
        if(all[0]) all[0].setAttribute('href', src);
        return;
      }
      var back=g.querySelector('.screen.only-' + theme + '.is-back');
      var front=back===all[0] ? all[1] : all[0];
      if(front.getAttribute('href')===src) return;   // already showing it
      var done=false;
      function flip(){
        if(done || gen!==swapGen) return;   // a newer request overtook this one
        done=true;
        back.classList.remove('is-back');
        front.classList.add('is-back');
      }
      back.addEventListener('load', flip, {once:true});
      back.addEventListener('error', flip, {once:true});   // still advance
      back.setAttribute('href', src);
      // The hidden theme has display:none and may never fire load, and a cached
      // image can resolve before the listener is attached. Neither should strand
      // the switcher on the old picture.
      if(!wait) flip(); else setTimeout(flip, 1200);
    }
    var dark=isDark();
    swap('light', list[i].light, !dark);
    swap('dark',  list[i].dark,   dark);
  }
  function screenLabel(k){
    var list=screens[k];
    return (list && list[shown[k] || 0]) ? list[shown[k] || 0].label : '';
  }

  /* ── caption ─────────────────────────────────────────────────────────────
     The slot says the same three things whatever the state — device, what is
     on its screen, where to read more. While a device is open it describes
     that one; at rest it describes the visitor's own, which is the device
     cycling its screens, so the words and the picture always agree.

     The authored feature ribbon is what shows when there is no such device: an
     unrecognised platform, or one with a single screenshot and so nothing to
     caption. `idleDev` is assigned once `mine` is known. */
  var idleDev=null;
  function captionDev(){ return open_ || idleDev; }

  function renderCaption(){
    if(!caption) return;
    var s=strings();
    var k=captionDev();
    if(!k){
      caption.classList.remove('in');
      caption.textContent='';
      if(ribbon) ribbon.classList.add('in');
      return;
    }
    if(ribbon) ribbon.classList.remove('in');
    var info=s[k];
    var list=screens[k] || [];
    // On a device's own page the name is in the headline already, so the
    // caption is just what is on the screen.
    caption.innerHTML=(solo ? '' : '<b></b>') + '<span class="cap-screen"></span>';
    if(!solo) caption.querySelector('b').textContent=info.name;
    // With several screens the label names the one on show; with one it stays
    // the device's blurb, which is all there is to say about it.
    caption.querySelector('.cap-screen').innerHTML =
      list.length > 1 ? screenLabel(k) : info.blurb;
    if(solo) caption.querySelector('.cap-screen').classList.add('is-lead');

    if(list.length > 1){
      var dots=document.createElement('span');
      dots.className='screen-dots';
      dots.setAttribute('role','group');
      list.forEach(function(scr, i){
        var d=document.createElement('button');
        d.type='button';
        d.className='screen-dot' + (i===(shown[k] || 0) ? ' is-on' : '');
        d.setAttribute('aria-pressed', String(i===(shown[k] || 0)));
        d.innerHTML='<span class="sr-only">'+scr.label+'</span>';
        d.addEventListener('click', function(e){
          e.stopPropagation();
          showScreen(k, i);
          renderCaption();
          startCycle();          // a manual step restarts the dwell
        });
        dots.appendChild(d);
      });
      caption.appendChild(dots);
    }

    var out=solo ? null : more[k];
    if(out && out.href){
      var a=document.createElement('a');
      a.className='cap-more';
      a.href=out.href;
      a.innerHTML=out.label;
      a.addEventListener('click', function(e){ e.stopPropagation(); });
      caption.appendChild(a);
    }
    caption.classList.add('in');
  }
  document.addEventListener('lz:lang', renderCaption);

  /* ── your device ───────────────────────────────────────────────────────
     A soft halo on the device you are actually reading this on. The e-reader
     can never win, and that is correct — nobody browses a website from one.
     An unrecognised platform highlights nothing and everything still works. */
  var mine={win:'laptop', mac:'laptop', linux:'laptop',
            android:'phone', ios:'phone'}[(window.lzPlatform && window.lzPlatform()) || ''];
  if(!solo && mine && devs[mine]) devs[mine].classList.add('is-yours');
  // Only a device with something to switch between earns the slot: with one
  // screenshot there is no carousel to caption, and the feature ribbon says
  // more than a line that never changes.
  if(!solo && mine && devs[mine] && (screens[mine] || []).length > 1) idleDev=mine;
  renderCaption();

  /* ── ribbon ──────────────────────────────────────────────────────────────
     One capability at a time, fading up as the last fades out. Under reduced
     motion the timer never starts and CSS lays the whole list out at once, so
     nothing is lost — it just stops moving. */
  /* The ribbon only runs when the caption has nothing to say — see renderCaption.
     Under reduced motion the timer never starts and CSS lays the whole list out
     at once, so nothing is lost; it just stops moving. */
  if(ribbon && !idleDev){
    var items=Array.prototype.slice.call(ribbon.querySelectorAll('.rib-item'));
    if(items.length){
      var at=0;
      items[0].classList.add('is-on');
      if(!reduced && items.length > 1){
        setInterval(function(){
          if(open_) return;            // a maximised device owns the slot
          var leaving=items[at];
          // .is-out carries it up and out; .is-on alone would only fade it,
          // and the two phrases would cross in the middle of the slot.
          leaving.classList.remove('is-on');
          leaving.classList.add('is-out');
          setTimeout(function(){ leaving.classList.remove('is-out'); }, 600);
          at=(at + 1) % items.length;
          items[at].classList.add('is-on');
        }, 3600);
      }
    }
  }

  /* ── hover / focus ─────────────────────────────────────────────────────
     SVG has no z-index: painting order is document order, so the device that
     should sit on top has to actually become the last sibling. That has to be
     undone afterwards — the artwork has a deliberate front-to-back order (the
     laptop sits behind both side devices), and without restoring it the last
     device hovered stays in front for good. */
  var devices=devs[ORDER[0]].parentNode;      // <g class="devices">
  var plane=devices.parentNode;               // its parent, above the ground
  // The drawn order, back to front, as authored.
  var drawn=Array.prototype.slice.call(devices.children);

  function raise(k){
    // Out of .devices entirely, so the group fade behind it never touches the
    // device in focus — and so the two left behind still occlude each other.
    if(devs[k].parentNode!==plane) plane.appendChild(devs[k]);
  }

  function restoreOrder(){
    if(devices.children.length===drawn.length) return;   // untouched
    drawn.forEach(function(node){ devices.appendChild(node); });
  }

  function heat(k){
    if(solo || open_) return;      // nothing to contrast a lone device against
    ORDER.forEach(function(x){ devs[x].classList.toggle('is-hot', x===k); });
    stage.classList.toggle('has-hot', !!k);
    if(k) raise(k); else restoreOrder();
  }

  /* ── full view ───────────────────────────────────────────────────────────
     A single corner control over the open device. It hands the whole screen
     set to the lightbox, so full view is a gallery too rather than a dead end. */
  var expand=document.createElement('button');
  expand.type='button';
  expand.className='stage-expand';
  expand.innerHTML=
    '<svg viewBox="0 0 24 24" width="18" height="18" fill="none" stroke="currentColor" ' +
    'stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">' +
    '<path d="M9 4H4v5M15 4h5v5M15 20h5v-5M9 20H4v-5"/></svg>' +
    '<span class="sr-only"><span lang="en">Open full size</span>' +
    '<span lang="uk">Відкрити на весь екран</span></span>';
  function openFull(origin){
    if(!open_) return;
    var list=screens[open_] || [];
    var device=open_;
    stopCycle();               // nothing should move behind an open lightbox
    window.lzZoom({
      src:fullSrc(device),
      alt:hits[device].textContent.trim(),
      returnTo:origin,
      index:shown[device] || 0,
      items:list.map(function(scr){
        return {full:isDark() ? scr.fullDark : scr.fullLight, label:scr.label};
      }),
      // Keep the device underneath on the same screen, so closing the lightbox
      // leaves the stage showing what was just being looked at.
      onChange:function(i){ showScreen(device, i); renderCaption(); },
      onClose:function(){ startCycle(); }
    });
  }
  expand.addEventListener('click', function(e){ e.stopPropagation(); openFull(expand); });
  // A solo page has one device, permanently open, so a corner control that only
  // ever means "this one" is chrome for its own sake — the device is the button.
  if(!solo) stage.parentNode.appendChild(expand);

  /* ── auto-advance ────────────────────────────────────────────────────────
     One device at a time cycles its own screens, so the switcher demonstrates
     itself rather than waiting to be found. Any manual step restarts the clock,
     and under reduced motion it never runs.

     Which device that is depends on the state:

       open     the one being looked at
       idle     the visitor's own — the same one wearing the halo, and the one
                the caption describes. Seeing the app move on the device you
                are holding is the point of the highlight; a device that is
                only outlined reads as decoration.

     Unrecognised platform highlights nothing, so nothing cycles either, and a
     device with a single screenshot is skipped — there is nothing to advance
     to. That is the phone today, until a second Android shot exists. */
  var cycle=null;
  function stopCycle(){ if(cycle){ clearInterval(cycle); cycle=null; } }
  function cycleTarget(){ return open_ || idleDev || null; }
  function startCycle(){
    stopCycle();
    if(reduced) return;
    var k=cycleTarget();
    if(!k || (screens[k] || []).length < 2) return;
    // Idle is background detail, not something to read, so it dwells longer
    // than the switcher does while a device is open and has the eye.
    cycle=setInterval(function(){
      var at=cycleTarget();
      if(at!==k){ startCycle(); return; }        // opened or closed under us
      showScreen(k, ((shown[k] || 0) + 1) % screens[k].length);
      renderCaption();
    }, open_ ? 4200 : 6000);
  }

  /* ── maximise ────────────────────────────────────────────────────────────
     Not a modal: the device grows inside the stage it already occupies, so
     there is no scroll lock and no focus trap to get wrong. */
  function fit(k){
    // Two boxes, and the difference matters: the transform scales about the
    // *group* centre (transform-box:fill-box), but the device has to be sized
    // and centred by its own body — the group's box also contains the halo,
    // which is far larger and would collapse the scale to about 1.1.
    var g=devs[k].getBBox();
    var b=devs[k].querySelector('.dev-body').getBBox();
    var gx=g.x + g.width / 2, gy=g.y + g.height / 2;
    var bx=b.x + b.width / 2, by=b.y + b.height / 2;
    var s=Math.min(vb.width / b.width, vb.height / b.height);
    // The body centre lands at groupCentre + s*(bodyCentre - groupCentre), so
    // solve for the translation that puts it at the centre of the viewBox.
    var dx=(vb.x + vb.width / 2) - gx - s * (bx - gx);
    var dy=(vb.y + vb.height / 2) - gy - s * (by - gy);
    return 'translate('+dx+'px,'+dy+'px) scale('+s+')';
  }

  function close(){
    // A solo stage has nothing to close down to — its device is the page. Escape
    // and the click-away handler both reach here while the lightbox is being
    // dismissed, and without this the stage would shut itself and go dead: no
    // caption, no switcher, and an expand button that returns early on !open_.
    if(solo) return;
    if(!open_) return;
    stopCycle();
    var k=open_; open_=null;
    devs[k].style.transform='';
    devs[k].classList.remove('is-open');
    hits[k].classList.remove('is-open');
    hits[k].setAttribute('aria-expanded','false');
    stage.classList.remove('is-max');
    stage.parentNode.classList.remove('is-max');
    restoreOrder();
    renderCaption();
    hits[k].focus();
    startCycle();          // back to the visitor's own device ticking over
  }

  function toggle(k){
    if(open_===k){ close(); return; }
    if(open_) close();
    heat(null);
    raise(k);
    open_=k;
    devs[k].classList.add('is-open');
    devs[k].style.transform=fit(k);
    // The open device's hotspot grows to cover the stage, so clicking the
    // enlarged artwork anywhere puts it back — which is what zoom-out implies.
    hits[k].classList.add('is-open');
    hits[k].setAttribute('aria-expanded','true');
    stage.classList.add('is-max');
    stage.parentNode.classList.add('is-max');
    renderCaption();
    startCycle();
  }

  ORDER.forEach(function(k){
    var btn=hits[k];
    btn.setAttribute('aria-expanded','false');
    btn.addEventListener('pointerenter', function(){ heat(k); });
    btn.addEventListener('pointerleave', function(){ heat(null); });
    btn.addEventListener('focus', function(){
      // Only for keyboard focus. close() restores focus to this button, and
      // heating on that left the device raised and dimmed-siblings after a
      // mouse close — including after switching tabs and back, since the
      // button keeps focus. :focus-visible is false for programmatic focus
      // that follows a click, and true when the user is on the keyboard.
      if(btn.matches(':focus-visible')) heat(k);
    });
    btn.addEventListener('blur', function(){ heat(null); });
    btn.addEventListener('click', function(){
      if(solo){ openFull(hits[k]); return; }   // already at size; the click means "bigger"
      toggle(k);
    });
    btn.addEventListener('keydown', function(e){
      if(e.key!=='ArrowRight' && e.key!=='ArrowLeft') return;
      e.preventDefault();
      var step=e.key==='ArrowRight' ? 1 : ORDER.length - 1;
      hits[ORDER[(ORDER.indexOf(k) + step) % ORDER.length]].focus();
    });
  });

  document.addEventListener('keydown', function(e){ if(e.key==='Escape') close(); });
  document.addEventListener('click', function(e){
    // A click anywhere outside the stage puts the hero back.
    if(open_ && !stage.parentNode.contains(e.target)) close();
  });
  window.addEventListener('resize', function(){
    if(open_) devs[open_].style.transform=fit(open_);
  });

  /* ── swipe ───────────────────────────────────────────────────────────────
     Only while a device is maximised — that is when the stage is a picture
     being looked at rather than three small ones being chosen between, and it
     keeps a flick across the idle hero from changing something the visitor was
     not aiming at. A solo page counts as open from the first paint, which is
     right: its device is the page. Any step restarts the dwell, exactly as
     tapping a dash does. */
  if(window.lzSwipe){
    window.lzSwipe(stage.parentNode, function(dir){
      if(!open_) return;
      var list=screens[open_] || [];
      if(list.length < 2) return;
      showScreen(open_, ((shown[open_] || 0) + dir + list.length) % list.length);
      renderCaption();
      startCycle();
    });
  }

  /* ── pointer parallax ────────────────────────────────────────────────────
     Fine pointers only: on touch there is no hover to parallax with, and
     under reduced motion it never binds at all. */
  if(!reduced && window.matchMedia && window.matchMedia('(pointer: fine)').matches){
    var wrap=stage.parentNode, frame=0;
    wrap.addEventListener('pointermove', function(e){
      if(frame) return;
      frame=requestAnimationFrame(function(){
        frame=0;
        if(open_) return;
        var r=stage.getBoundingClientRect();
        stage.style.setProperty('--px', ((e.clientX-r.left)/r.width * 2 - 1).toFixed(3));
        stage.style.setProperty('--py', ((e.clientY-r.top)/r.height * 2 - 1).toFixed(3));
      });
    });
    wrap.addEventListener('pointerleave', function(){
      stage.style.setProperty('--px', 0);
      stage.style.setProperty('--py', 0);
    });
  }

  /* ── solo bootstrap ──────────────────────────────────────────────────────
     A one-device stage is already framed on its device, so there is no
     maximise step: mark it open so the caption, the screen switcher and the
     full-size control are live from the first paint, and let it cycle. */
  if(solo){
    open_=solo;
    renderCaption();
  }
  startCycle();
})();
